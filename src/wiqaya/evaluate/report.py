"""Generate docs/EVALUATION.md from the latest simulation and model runs (PROMPT.md §7)."""

from __future__ import annotations

import json
from typing import Any

from wiqaya.common.paths import DOCS, RUNS_DIR

METRIC_LABELS = {
    "people_with_gaps": "People with open gaps",
    "targeted_people": "People on the policy's list",
    "contacts": "Contacts (messages, calls, CHW visits)",
    "people_contacted": "People contacted",
    "reach_pct": "Reach: % of people with gaps contacted",
    "completed_visits": "Completed screenings / WCVs",
    "completed_per_100_contacts": "**Completed per 100 contacts (primary endpoint)**",
    "gaps_closed_pct": "% of open gaps closed in 12 weeks",
    "median_days_to_attendance": "Median days from T0 to attendance",
    "followup_completion_pct": "Follow-up completion for abnormal results (%)",
    "false_positive_rate_pct": "FP rate: high priority but screen normal (%)",
    "false_negative_rate_pct": "FN rate: latent condition but not reached (%)",
    "screen_false_positive_referrals": "False-positive screening referrals",
    "decline_optout_pct": "Decline / opt-out rate (%)",
    "reviewer_override_pct": "Reviewer override (rejection) rate (%)",
    "flags_per_slot": "Flags per available slot",
    "bundled_messages": "Household-bundled messages",
    "van_visits": "Mobile-van visits",
    "chw_contacts": "Community health worker contacts",
}


def _fmt(v: Any) -> str:
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v:,.2f}"
    return f"{v:,}" if isinstance(v, int) else str(v)


def _table(header: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(_fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render(sim: dict[str, Any], models: dict[str, Any]) -> str:
    b, w = sim["policies"]["baseline"], sim["policies"]["wiqaya"]
    pe = sim["primary_endpoint"]
    L: list[str] = [
        "# Evaluation — Simulated cohort",
        "",
        "> **Simulated cohort.** Every number here comes from a synthetic population and a simulated 12-week period "
        f"(run `{sim['run_id']}`, T0 = {sim['as_of']}). None of it is real-world evidence. "
        "Generated by `make evaluate`; do not edit by hand.",
        "",
        "## Headline",
        "",
        f"- Primary endpoint, **{pe['name']}**: baseline **{_fmt(pe['baseline'])}**, Wiqaya **{_fmt(pe['wiqaya'])}** "
        f"(difference {pe['difference']:+.2f}).",
        f"- Both policies had the same capacity ({sim['capacity_slots']:,} slots over {sim['weeks']} weeks), the same "
        "invitation budget per slot and the same random draws per person (common random numbers).",
        "- **Baseline:** today's practice. Age/sex-rule eligibility, most overdue first, one generic SMS in Arabic or "
        "English, no bundling.",
        "- **Wiqaya:** the full pipeline. Rule-based gaps plus follow-up and cascade, ranking with the fairness floor, "
        "and a simulated reviewer who accepts 90% of flags. Contact uses consented channels in the preferred language, "
        "household bundling, the mobile van, up to 3 touches and a CHW visit after 2 non-responses.",
        "",
        *(
            [
                f"- **Trade-off to note:** Wiqaya contacts fewer distinct people (reach {w['reach_pct']}% vs "
                f"{b['reach_pct']}%). It spends repeat touches, CHW visits and bundled messages on the people it "
                "prioritises, instead of one SMS to everyone. Fewer people are touched, but more visits are completed "
                f"({w['completed_visits']:,} vs {b['completed_visits']:,}) and more gaps are closed. A pilot should decide "
                "this balance explicitly; `invites_per_slot` and `max_touches` in config/simulation.yaml control it."
            ]
            if w["reach_pct"] < b["reach_pct"]
            else []
        ),
        "",
        "## Baseline vs Wiqaya",
        "",
        _table(["Metric", "Baseline", "Wiqaya"], [[METRIC_LABELS[k], b.get(k), w.get(k)] for k in METRIC_LABELS]),
        "",
        "### Yield per 1,000 screened (simulated detections)",
        "",
        _table(
            ["Condition", "Baseline", "Wiqaya"],
            [
                [k, b["yield_per_1000_screened"].get(k), w["yield_per_1000_screened"].get(k)]
                for k in sorted(set(b["yield_per_1000_screened"]) | set(w["yield_per_1000_screened"]))
            ],
        ),  # fmt: skip
        "",
        "## Equity: results by segment",
        "",
        "Cells covering fewer than 11 people are shown as `suppressed (n<11)`. A per-100-contacts cell is blank when "
        "fewer than 11 contacts were made. Nationality, language, district and insurance tier are monitoring "
        "segments only: they are **not** inputs to the risk model.",
        "",
    ]
    for seg in sim["segments"]["wiqaya"]:
        bs = {r["segment"]: r for r in sim["segments"]["baseline"][seg]}
        rows = []
        for r in sim["segments"]["wiqaya"][seg]:
            br = bs.get(r["segment"], {})
            rows.append([r["segment"], r["n"], br.get("reach_pct"), r["reach_pct"], br.get("completed_per_100_contacts"),
                         r["completed_per_100_contacts"], br.get("gaps_closed_pct"), r["gaps_closed_pct"]])  # fmt: skip
        L += [f"### {seg.replace('_', ' ').title()}", "",
              _table(["Segment", "n", "Reach % (B)", "Reach % (W)", "Per 100 contacts (B)", "Per 100 contacts (W)",
                      "Gaps closed % (B)", "Gaps closed % (W)"], rows), ""]  # fmt: skip
    mr, mn = models["model_r"], models["model_n"]

    def cal_rows(m: dict[str, Any]) -> list[list[Any]]:
        c, u = m["test_calibrated"], m["test_uncalibrated"]
        return [["AUROC", u.get("auroc"), c.get("auroc")], ["Brier score", u.get("brier"), c.get("brier")],
                ["Calibration slope", u.get("calibration_slope"), c.get("calibration_slope")],
                ["Calibration intercept", u.get("calibration_intercept"), c.get("calibration_intercept")],
                ["Held-out n", c.get("n"), c.get("n")], ["Outcome prevalence", c.get("prevalence"), c.get("prevalence")]]  # fmt: skip

    L += [
        "## Models (held-out people)",
        "",
        f"**Model R: risk elevation.** Label: {mr['label']}. Reference date {mr['reference_date']}. "
        f"Train {mr['n_train']}, calibration {mr['n_calibration']}, test {mr['n_test']} people.",
        "",
        _table(["Metric", "Uncalibrated", "Isotonic-calibrated"], cal_rows(mr)),
        "",
        "Reliability curve (calibrated, held-out):",
        "",
        _table(
            ["Bin", "n", "Mean predicted", "Observed rate"],
            [[r["bin"], r["n"], r["mean_predicted"], r["observed_rate"]] for r in mr["test_calibrated"]["reliability"]],
        ),
        "",
        f"**Model N: no-show.** Label: {mn['label']}. Train {mn['n_train']}, calibration {mn['n_calibration']}, "
        f"test {mn['n_test']} invitations.",
        "",
        _table(["Metric", "Uncalibrated", "Isotonic-calibrated"], cal_rows(mn)),
        "",
        "Per-segment calibration for Model R. Segments with fewer than 100 held-out people show "
        '"Model not validated for this segment":',
        "",
    ]
    rows = []
    for seg, vals in mr["segments"].items():
        for v, s in vals.items():
            rows.append([seg, v, s["n"], s.get("auroc", s.get("status")), s.get("calibration_slope"), s.get("brier")])
    L += [_table(["Segment", "Value", "n", "AUROC / status", "Slope", "Brier"], rows), ""]
    sens = sim.get("sensitivity", {})
    L += [
        "## Sensitivity analysis: does the simulator flatter Wiqaya?",
        "",
        "The response model is ours, so it could be built to favour our own design. To test this, we re-ran both "
        "policies with weaker or stronger response effects. The table shows how the Wiqaya-vs-baseline difference "
        "changes:",
        "",
        _table(
            ["Scenario", "Override", "Baseline /100", "Wiqaya /100", "Difference", "Gaps closed % B → W", "FN % B → W"],
            [
                [
                    "main",
                    "—",
                    pe["baseline"],
                    pe["wiqaya"],
                    pe["difference"],
                    f"{b['gaps_closed_pct']} → {w['gaps_closed_pct']}",
                    f"{b['false_negative_rate_pct']} → {w['false_negative_rate_pct']}",
                ]
            ]
            + [
                [
                    k,
                    json.dumps(v["override"]),
                    v["baseline_per_100"],
                    v["wiqaya_per_100"],
                    v["difference"],
                    f"{v['baseline_gaps_closed_pct']} → {v['wiqaya_gaps_closed_pct']}",
                    f"{v['baseline_fn_pct']} → {v['wiqaya_fn_pct']}",
                ]
                for k, v in sens.items()
            ],
        ),  # fmt: skip
        "",
    ]
    diffs = {k: v["difference"] for k, v in sens.items()}
    if diffs:
        worst = min(diffs, key=lambda k: diffs[k])
        L += [f"How to read this: the advantage is smallest under **{worst}** ({diffs[worst]:+.2f} per 100 contacts). "
              "Language matching, bundling and the van are all levers inside the simulator, so the size of the gain "
              "depends on assumed effect sizes that have not been measured in Abu Dhabi. The direction of the result "
              "is more robust than its size. Only a real pilot with randomised outreach can establish the effect.", ""]  # fmt: skip
    L += [
        "## TRIPOD+AI-style checklist",
        "",
        _table(
            ["Item", "Covered?", "Where / note"],
            [
                [
                    "Source of data, synthetic nature declared",
                    "Yes",
                    "DATA_PROVENANCE.md; every screen labelled Simulated cohort",
                ],
                ["Eligibility and outcome definitions", "Yes", "Model R/N labels above; MODEL_CARD.md"],
                ["Predictors and exclusions (no nationality/language)", "Yes", "models/features.py, asserted in tests"],
                [
                    "Sample size and missing data handling",
                    "Partly",
                    "n reported; missing labs kept as NaN (LightGBM native)",
                ],
                ["Temporal separation of features and outcome", "Yes", "features before reference date; label after"],
                [
                    "Internal validation (held-out people)",
                    "Yes",
                    "person-level split; isotonic calibration on separate split",
                ],
                ["Calibration (slope, intercept, Brier, curve)", "Yes", "tables above"],
                ["Performance by subgroup", "Yes", "per-segment table; n<100 not validated"],
                ["External validation", "No", "not possible without real data; required before any pilot"],
                [
                    "Clinical utility / decision impact",
                    "Simulated only",
                    "baseline vs Wiqaya above; needs a randomised pilot",
                ],
                ["Fairness assessment", "Yes", "fairness floor + equity tables; segments not used as predictors"],
                ["Human oversight", "Yes", "reviewer step; cascade requires clinician sign-off"],
                ["Model updating / monitoring plan", "Partly", "MODEL_CARD.md update policy"],
                ["Code and data availability", "Yes", "repository; seeded, byte-identical regeneration"],
            ],
        ),
        "",
    ]
    return "\n".join(L)


def write() -> str:
    sim = json.loads((RUNS_DIR / "simulation.json").read_text(encoding="utf-8"))
    models = json.loads((RUNS_DIR / "models.json").read_text(encoding="utf-8"))
    text = render(sim, models)
    (DOCS / "EVALUATION.md").write_text(text, encoding="utf-8")
    return text
