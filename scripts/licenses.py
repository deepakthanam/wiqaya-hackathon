"""Generate docs/THIRD_PARTY_LICENSES.md from installed Python packages and `pnpm licenses`."""

from __future__ import annotations

import json
import subprocess
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

STATIC = [
    ("HAPI FHIR JPA Server Starter (Docker image hapiproject/hapi)", "Apache-2.0", "service"),
    ("PostgreSQL", "PostgreSQL License", "service"),
    ("Caddy", "Apache-2.0", "service (deployment)"),
    ("OpenStreetMap data and tiles", "ODbL 1.0 (data); tile usage policy – attribution shown in app", "data"),
    ("NCBI ClinVar", "Public NCBI data – attribution", "data"),
    ("LOINC codes", "LOINC licence (Regenstrief) – codes used with attribution", "terminology"),
    ("SNOMED CT concept ids", "SNOMED CT affiliate licence required for production use", "terminology"),
    ("CVX codes", "CDC – public domain", "terminology"),
    ("HL7 FHIR / terminology.hl7.org", "CC0 / HL7 licence", "standard"),
]


def python_rows() -> list[tuple[str, str, str]]:
    rows = []
    for d in metadata.distributions():
        name = d.metadata.get("Name") or "?"
        if name.lower() == "wiqaya":
            continue
        lic = d.metadata.get("License-Expression") or d.metadata.get("License") or ""
        if not lic or len(lic) > 60:
            classifiers = [
                c.split("::")[-1].strip() for c in d.metadata.get_all("Classifier") or [] if c.startswith("License")
            ]
            lic = ", ".join(classifiers) or (lic[:57] + "…" if lic else "see package")
        rows.append((f"{name} {d.version}", lic.replace("|", "/"), "python"))
    return sorted(set(rows), key=lambda r: r[0].lower())


def node_rows() -> list[tuple[str, str, str]]:
    try:
        out = subprocess.run(["corepack", "pnpm", "licenses", "list", "--json", "--prod"], cwd=ROOT / "web",
                             capture_output=True, text=True, check=True, shell=False).stdout  # fmt: skip
        data = json.loads(out)
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError):
        return [("(run `corepack pnpm licenses list` in web/)", "n/a", "node")]
    rows = []
    for lic, pkgs in data.items():
        for p in pkgs:
            for v in p.get("versions", [p.get("version", "")]):
                rows.append((f"{p['name']} {v}", lic, "node (production)"))
    return sorted(rows, key=lambda r: r[0].lower())


def main() -> None:
    rows = STATIC + python_rows() + node_rows()
    lines = ["# Third-party licences", "", "Generated by `make licenses` (`scripts/licenses.py`). Do not edit by hand.", "",
             "| Component | Licence | Kind |", "|---|---|---|"]  # fmt: skip
    lines += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    (ROOT / "docs" / "THIRD_PARTY_LICENSES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/THIRD_PARTY_LICENSES.md ({len(rows)} entries)")


if __name__ == "__main__":
    main()
